#!/usr/bin/env python3
"""Fail-closed G-5 comparison requiring full, compatible official 1M/10M evidence."""
import json
import math
import statistics
from collections import Counter
from pathlib import Path

from validation import FAMILIES, RANGES, expected_http_coverage, inspect_http_artifact

RESULTS = Path(__file__).parent / "results"
ONE_M = RESULTS / "benchmark-1000000.json"
TEN_M = RESULTS / "benchmark-10000000.json"


def roles(scale):
    last = 10 if scale == 1_000_000 else 100
    return {1: "hot", 2: "second", 3: "middle", last: "small"}


def normalize_workload(workload):
    return {key: value for key, value in workload.items()
            if key not in ("sequential_tenant_roles", "concurrent_tenant_roles")}


def build_expected_cases(scale):
    expected = Counter()
    tenant_roles = roles(scale)
    for (tenant, family, grain, range_name, mode), count in expected_http_coverage(scale).items():
        case = (tenant_roles[tenant], family, grain, range_name, mode)
        expected[case] += count
    return expected


def validate_artifact(artifact, scale):
    if not isinstance(artifact, dict):
        return ["benchmark artifact missing or invalid"]
    errors = inspect_http_artifact(artifact, scale)
    dataset = artifact.get("dataset") if isinstance(artifact.get("dataset"), dict) else {}
    if dataset.get("official_compatibility") != "VERIFIED":
        errors["metadata"].append("official dataset compatibility is not verified")
    if not dataset.get("generator_version") or dataset.get("manifest_version") != 1:
        errors["metadata"].append("official generator manifest/version is incomplete")
    return [message for group in errors.values() for message in group]


def compare_artifacts(one_m, ten_m):
    result = {"target": "G-5", "status": "NOT TESTED", "cases": [], "errors": []}
    a_errors = validate_artifact(one_m, 1_000_000)
    b_errors = validate_artifact(ten_m, 10_000_000)
    if a_errors or b_errors:
        result["errors"] = [{"scale": "1M", "reasons": a_errors}, {"scale": "10M", "reasons": b_errors}]
        result["reason"] = "Both complete artifacts must prove official dataset identity, scale, tenant distribution, workload, zero errors, and complete coverage."
        return result

    da, db = one_m["dataset"], ten_m["dataset"]
    if any(da.get(k) != db.get(k) for k in ("dataset_id", "generator_id", "generator_version", "seed", "official_compatibility", "manifest_version")):
        result["errors"].append("1M and 10M datasets are not generated by the same declared official dataset contract")
    if normalize_workload(one_m["workload"]) != normalize_workload(ten_m["workload"]):
        result["errors"].append("1M and 10M workload parameters differ")
    ha, hb = one_m.get("hardware", {}), ten_m.get("hardware", {})
    if any(ha.get(k) is None or hb.get(k) is None or ha.get(k) != hb.get(k)
           for k in ("platform", "machine", "processor", "logical_cpus", "ram_bytes")):
        result["errors"].append("1M and 10M hardware differs")
    pg_a = one_m.get("run", {}).get("postgres_version")
    pg_b = ten_m.get("run", {}).get("postgres_version")
    if not pg_a or pg_a != pg_b:
        result["errors"].append("PostgreSQL versions differ or are missing")
    if result["errors"]:
        return result

    expected_a, expected_b = build_expected_cases(1_000_000), build_expected_cases(10_000_000)
    if expected_a != expected_b:
        result["errors"].append("registered scale-specific workload coverage differs")
        return result

    def case_samples(artifact, scale):
        role = roles(scale)
        samples = {}
        for item in artifact["requests"]:
            case = (role[item["tenant"]], item["family"], item["grain"], item["range"], item["mode"])
            samples.setdefault(case, []).append(item["ms"])
        return samples

    cases_a, cases_b = case_samples(one_m, 1_000_000), case_samples(ten_m, 10_000_000)
    if set(cases_a) != set(expected_a) or set(cases_b) != set(expected_b):
        result["errors"].append("one or both benchmark artifacts have missing or unexpected case keys")
        return result
    for key, expected_count in expected_a.items():
        if len(cases_a[key]) != expected_count or len(cases_b[key]) != expected_count:
            result["errors"].append(f"case {key} expected {expected_count} observations at both scales")
    if result["errors"]:
        return result

    def percentile(values, q):
        ordered = sorted(values)
        return ordered[min(len(ordered) - 1, math.ceil(q * len(ordered)) - 1)]

    for key in sorted(expected_a):
        a, b = cases_a[key], cases_b[key]
        ratios = {"p50": statistics.median(b) / statistics.median(a),
                  "p95": percentile(b, .95) / percentile(a, .95),
                  "max": max(b) / max(a)}
        result["cases"].append({"case": list(key), "n_1m": len(a), "n_10m": len(b),
                                "latency_1m_ms": {"p50": statistics.median(a), "p95": percentile(a, .95), "max": max(a)},
                                "latency_10m_ms": {"p50": statistics.median(b), "p95": percentile(b, .95), "max": max(b)},
                                "ratios_10m_over_1m": ratios,
                                "status": "PASS" if max(ratios.values()) < 2 else "FAIL"})
    result.update({"status": "PASS" if all(x["status"] == "PASS" for x in result["cases"]) else "FAIL",
                   "dataset_metadata": {"1m": {"dataset": one_m["dataset"], "source_snapshot": one_m["source_snapshot"], "run": one_m["run"]},
                                        "10m": {"dataset": ten_m["dataset"], "source_snapshot": ten_m["source_snapshot"], "run": ten_m["run"]}},
                   "hardware": ha, "workload": normalize_workload(one_m["workload"]),
                   "comparison": "Every expected tenant-role/query/range/concurrency case; p50/p95/max; zero request errors; same verified official dataset contract and hardware."})
    return result


def main():
    if not ONE_M.exists() or not TEN_M.exists():
        result = {"target": "G-5", "status": "NOT TESTED", "reason": "A current valid 1M and 10M benchmark artifact pair is required.", "cases": [], "errors": []}
    else:
        try:
            result = compare_artifacts(json.loads(ONE_M.read_text()), json.loads(TEN_M.read_text()))
        except Exception as exc:
            result = {"target": "G-5", "status": "NOT TESTED", "reason": f"Artifact parsing/validation error: {type(exc).__name__}", "cases": [], "errors": [str(exc)]}
    (RESULTS / "growth.json").write_text(json.dumps(result, indent=2))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
